export const plantById = (id) => PLANTS.find((p) => p.id === id);

export function matchesGoal(plant, goalId) {
  switch (goalId) {
    case 'hummingbirds':
      return plant.wildlife.includes('Hummingbirds');
    case 'bees':
      return plant.wildlife.includes('Native bees');
    case 'butterflies':
      return plant.wildlife.includes('Butterflies');
    case 'birds':
      return plant.wildlife.includes('Birds');
    case 'water':
      return plant.water === 'Very low';
    case 'cover':
      return plant.form !== 'tree';
    case 'shade':
      return plant.sun === 'Part shade' || plant.form === 'tree';
    default:
      return true;
  }
}